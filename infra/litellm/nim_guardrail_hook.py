"""
NIMFlagshipGuardrailHook — LiteLLM Guardrail and Pre-Call Injection Hook.
Enforces the 100% Frontier Heavyweight NIM Model Matrix (> 250B).
Blocks lightweight, flash, and browser-quantized micro models.
Injects 'reasoning_effort: max' for DeepSeek-R1 / Nemotron and 4096d embedding params.
"""

import os
import re
import json
import logging
from typing import Any, Dict, Optional

logger = logging.getLogger("NIMFlagshipGuardrailHook")
logger.setLevel(logging.INFO)

# Unauthorized lightweight / flash / micro models strictly prohibited from production LOT-AIOS
PROHIBITED_MODELS = {
    "llama-3.2-1b",
    "llama-3.2-3b",
    "qwen-2.5-0.5b",
    "qwen-2.5-1.5b",
    "qwen-2.5-3b",
    "gemma-2-2b",
    "gpt-4o-mini",
    "claude-3-haiku",
    "phi-3-mini",
    "smollm",
    "tinyllama",
}

# Flagship models requiring maximum reasoning effort
REASONING_FLAGSHIP_MODELS = {
    "deepseek-v4-pro",
    "deepseek-ai/deepseek-v4-pro",
    "deepseek-r1",
    "deepseek-ai/deepseek-r1",
    "nemotron-3-ultra-550b",
    "nvidia/nemotron-3-ultra-550b",
    "llama-3.1-nemotron-ultra-253b",
    "nvidia/llama-3.1-nemotron-ultra-253b",
}

# Embedder models requiring exact 4096-dimensional output
EMBEDDER_MODELS = {
    "nemotron-3.5-embed-8b",
    "nvidia/nemotron-3.5-embed-8b",
}


class NIMFlagshipGuardrailHook:
    """
    LiteLLM Custom Logger / Pre-Call Guardrail Hook for NVIDIA NIM.
    """

    def __init__(self):
        logger.info("Initializing NIMFlagshipGuardrailHook with 100% Heavyweight Model Matrix Enforcement.")

    async def async_pre_call_hook(
        self,
        user_api_key_dict: Optional[Dict[str, Any]],
        cache: Any,
        data: Dict[str, Any],
        call_type: str,
    ) -> Optional[Dict[str, Any]]:
        """
        Intercepts requests before dispatching to provider endpoint.
        Validates model tier, injects reasoning flags, and enforces embedding dimension constraints.
        """
        model = data.get("model", "").lower()

        # 1. Block prohibited lightweight or flash models
        for prohibited in PROHIBITED_MODELS:
            if prohibited in model:
                raise ValueError(
                    f"[NIM Guardrail Violation] Model '{model}' is prohibited. "
                    f"LOT AIOS operates exclusively on 100% Frontier Heavyweight models (> 250B)."
                )

        # 2. Inject maximum reasoning effort for frontier reasoning models
        for reasoning_model in REASONING_FLAGSHIP_MODELS:
            if reasoning_model in model:
                data["reasoning_effort"] = "max"
                if "extra_body" not in data:
                    data["extra_body"] = {}
                data["extra_body"]["reasoning_effort"] = "max"
                data["extra_body"]["chat_template_args"] = {"enable_reasoning": True}
                break

        # 3. Enforce 4096 dimensions for Nemotron 3.5 Embed 8B
        for embed_model in EMBEDDER_MODELS:
            if embed_model in model:
                data["dimensions"] = 4096
                data["encoding_format"] = "float"
                break

        return data

    async def async_post_call_success_hook(
        self,
        data: Dict[str, Any],
        user_api_key_dict: Optional[Dict[str, Any]],
        response: Any,
    ) -> Any:
        """
        Post-call validation and markdown JSON repair if required.
        """
        return response

    async def async_post_call_failure_hook(
        self,
        request_data: Dict[str, Any],
        original_exception: Exception,
        user_api_key_dict: Optional[Dict[str, Any]],
    ) -> None:
        """
        Logs failures for circuit breaker and failover tracking.
        """
        logger.warning(
            f"[NIM Gateway Failover Notice] Model: {request_data.get('model')} - Exception: {str(original_exception)}"
        )


def repair_markdown_json(raw_text: str) -> Optional[Dict[str, Any]]:
    """
    Repairs malformed or fenced JSON strings generated by LLMs.
    """
    if not raw_text:
        return None
    # Strip markdown fences
    cleaned = re.sub(r"^```(?:json)?\s*", "", raw_text.strip(), flags=re.MULTILINE)
    cleaned = re.sub(r"\s*```$", "", cleaned.strip(), flags=re.MULTILINE)

    # Find outermost matching braces
    start = cleaned.find("{")
    end = cleaned.rfind("}")
    if start != -1 and end != -1 and end > start:
        candidate = cleaned[start : end + 1]
        try:
            return json.loads(candidate)
        except Exception:
            # Attempt trailing comma fix
            candidate = re.sub(r",\s*([\]}])", r"\1", candidate)
            try:
                return json.loads(candidate)
            except Exception:
                return None
    return None
